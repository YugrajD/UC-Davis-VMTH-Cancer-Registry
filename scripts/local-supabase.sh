#!/bin/bash
# Stand up a local Supabase (Auth + Postgres) for development, so dev work
# never touches the hosted project.
#
#   ./scripts/local-supabase.sh up       start the stack, load the schema, create dev users, write .env.local-supabase
#   ./scripts/local-supabase.sh reset    wipe the local database and rebuild it
#   ./scripts/local-supabase.sh users    (re)create the dev users only
#   ./scripts/local-supabase.sh status   show local URLs and the dev users
#   ./scripts/local-supabase.sh down     stop the stack
#
# Then run the app against it:
#   docker compose --env-file .env.local-supabase up --build backend frontend ml-worker

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENV_FILE=".env.local-supabase"
# Schema-only pg_dump of the hosted project's public schema. Regenerate with:
#   pg_dump "$DATABASE_URL_SYNC" --schema=public --schema-only --no-owner --no-privileges \
#     --file=database/baseline_schema.sql
BASELINE="database/baseline_schema.sql"
DEV_PASSWORD="${DEV_PASSWORD:-password123}"
ADMIN_EMAIL="admin@example.com"
UPLOADER_EMAIL="uploader@example.com"
REVIEWER_EMAIL="reviewer@example.com"

die() { echo "Error: $*" >&2; exit 1; }

check_prereqs() {
  command -v supabase >/dev/null || die "Supabase CLI not found. Install: brew install supabase/tap/supabase"
  command -v psql >/dev/null || die "psql not found. Install: brew install libpq && brew link --force libpq"
  command -v curl >/dev/null || die "curl not found."
  docker info >/dev/null 2>&1 || die "Docker is not running."
  [ -f "$BASELINE" ] || die "$BASELINE not found."
  # pg_dump 18 emits \restrict lines, which only recent psql releases understand.
  local major
  major="$(psql --version | grep -oE '[0-9]+' | head -1)"
  [ "$major" -ge 17 ] || die "psql $major is too old to load $BASELINE; need 17 or newer."
}

# Sets API_URL, DB_URL, ANON_KEY, SERVICE_ROLE_KEY and JWT_SECRET from the running stack.
load_status() {
  local out v
  out="$(supabase status -o env 2>/dev/null)" || die "Local Supabase is not running. Run: $0 up"
  eval "$out"
  for v in API_URL DB_URL ANON_KEY SERVICE_ROLE_KEY JWT_SECRET; do
    [ -n "${!v:-}" ] || die "supabase status did not report $v"
  done
}

# The baseline is the raw pg_dump file. The only thing done to it at load time is
# dropping its CREATE SCHEMA line, because a fresh database already has "public".
# Extensions are not part of a --schema=public dump, so create them first, in
# "public" to match the hosted project.
apply_schema() {
  load_status
  if [ "$(psql "$DB_URL" -Atc "SELECT to_regclass('public.patients') IS NOT NULL")" = "t" ]; then
    echo "Schema already loaded (use '$0 reset' to rebuild)."
    return
  fi
  echo "Loading $BASELINE..."
  psql "$DB_URL" -v ON_ERROR_STOP=1 -q <<'SQL'
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
SQL
  sed '/^CREATE SCHEMA public;$/d' "$BASELINE" | psql "$DB_URL" -v ON_ERROR_STOP=1 -q -o /dev/null
}

create_user() {
  local email="$1" code
  code="$(curl -s -o /dev/null -w '%{http_code}' -X POST "$API_URL/auth/v1/admin/users" \
    -H "apikey: $SERVICE_ROLE_KEY" -H "Authorization: Bearer $SERVICE_ROLE_KEY" \
    -H "Content-Type: application/json" \
    -d "{\"email\":\"$email\",\"password\":\"$DEV_PASSWORD\",\"email_confirm\":true}")"
  case "$code" in
    200|201) echo "  created $email" ;;
    422)     echo "  exists  $email" ;;
    *)       die "creating $email failed (HTTP $code)" ;;
  esac
}

create_users() {
  load_status
  echo "Creating dev users (password: $DEV_PASSWORD)..."
  create_user "$ADMIN_EMAIL"
  create_user "$UPLOADER_EMAIL"
  create_user "$REVIEWER_EMAIL"
}

# The backend runs in a container, where 127.0.0.1 is the container itself, so it
# reaches the host-published Supabase ports via host.docker.internal. The browser
# (frontend) uses 127.0.0.1.
write_env() {
  load_status
  local port="${DB_URL##*:}"
  port="${port%%/*}"
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/local-supabase.sh for the local Supabase stack. Do not commit.
DATABASE_URL=postgresql+asyncpg://postgres:postgres@host.docker.internal:${port}/postgres
DATABASE_URL_SYNC=postgresql://postgres:postgres@host.docker.internal:${port}/postgres
CORS_ORIGINS=["http://localhost:5173"]

SUPABASE_JWT_SECRET=${JWT_SECRET}
LOCAL_SUPABASE_URL=${API_URL/127.0.0.1/host.docker.internal}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}
VITE_SUPABASE_URL=${API_URL}
VITE_SUPABASE_ANON_KEY=${ANON_KEY}

ADMIN_EMAILS=${ADMIN_EMAIL}
UPLOADER_EMAILS=${UPLOADER_EMAIL}
REVIEWER_EMAILS=${REVIEWER_EMAIL}
EOF
  echo "Wrote $ENV_FILE"
}

print_summary() {
  load_status
  cat <<EOF

Local Supabase is running.
  API:     $API_URL
  Studio:  http://127.0.0.1:54323
  Inbox:   http://127.0.0.1:54324  (auth emails)
  DB:      $DB_URL
  Users:   $ADMIN_EMAIL (admin), $UPLOADER_EMAIL, $REVIEWER_EMAIL  /  $DEV_PASSWORD

Run the app:
  docker compose --env-file $ENV_FILE up --build backend frontend ml-worker
EOF
}

case "${1:-}" in
  up)
    check_prereqs
    supabase start
    apply_schema
    create_users
    write_env
    print_summary
    ;;
  reset)
    check_prereqs
    supabase db reset --local
    apply_schema
    create_users
    write_env
    print_summary
    ;;
  users)  check_prereqs; create_users ;;
  status) check_prereqs; print_summary ;;
  down)   check_prereqs; supabase stop ;;
  *) echo "Usage: $0 {up|reset|users|status|down}"; exit 1 ;;
esac
